'use strict';
// probe：只读探查 —— events/claims 列与 actor_seat 语义 + 检测器实跑口径
const Database = require('E:/music player/p1a-terminal/node_modules/better-sqlite3');
const dbPath = 'E:/music player/p1a-terminal/data/p1a.db';
const db = new Database(dbPath, { readonly: true });
const cols = (t) => db.prepare('PRAGMA table_info(' + t + ')').all().map(r => r.name).join(',');
console.log('events cols:', cols('events'));
console.log('claims cols:', cols('claims'));
console.log('players cols:', cols('players'));
console.log('games cols:', cols('games'));
console.log('--- sample events (actor_seat) ---');
console.log(JSON.stringify(db.prepare('SELECT id,game_id,seq,day,phase,type,actor_seat,substr(raw_text,1,30) AS t FROM events WHERE actor_seat IS NOT NULL LIMIT 5').all(), null, 0));
console.log('--- actor_seat: players.id vs seat ---');
console.log(JSON.stringify(db.prepare('SELECT e.actor_seat AS aseat, p.id AS pid, p.seat AS pseat, p.game_id AS pgid, e.game_id AS egid FROM events e LEFT JOIN players p ON p.id = e.actor_seat WHERE e.actor_seat IS NOT NULL LIMIT 6').all()));
console.log('match(correct-as-player-id) count:', JSON.stringify(db.prepare('SELECT COUNT(*) AS n FROM events e JOIN players p ON p.id=e.actor_seat WHERE e.actor_seat IS NOT NULL').get()));
console.log('as-seat-number fallback count:', JSON.stringify(db.prepare('SELECT COUNT(*) AS n FROM events e JOIN players p ON p.game_id=e.game_id AND p.seat=e.actor_seat WHERE e.actor_seat IS NOT NULL').get()));
console.log('game_type distinct:', JSON.stringify(db.prepare('SELECT game_type, COUNT(*) n FROM games GROUP BY game_type').all()));
console.log('preds w/ evidence:', JSON.stringify(db.prepare("SELECT COUNT(*) n FROM predictions WHERE evidence_json IS NOT NULL AND evidence_json != '' AND evidence_json != '[]'").get()));
console.log('preds total:', JSON.stringify(db.prepare('SELECT COUNT(*) n FROM predictions').get()));
console.log('pred layer dist:', JSON.stringify(db.prepare('SELECT layer, COUNT(*) n FROM predictions GROUP BY layer').all()));
