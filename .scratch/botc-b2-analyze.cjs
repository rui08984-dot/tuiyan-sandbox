const fs = require("fs");
const raw = JSON.parse(fs.readFileSync("E:/music player/docs/sandbox/botc-adapt/data/roles-zh.json", "utf8"));
console.log("total roles:", raw.length);
const notes = {};
for (const r of raw) notes[r.unique_note] = (notes[r.unique_note] || 0) + 1;
console.log("unique_note values:", JSON.stringify(notes, null, 2));
const teams = {};
for (const r of raw) teams[r.team] = (teams[r.team] || 0) + 1;
console.log("team values:", JSON.stringify(teams));
const eds = {};
for (const r of raw) for (const e of (r.editions||[])) eds[e] = (eds[e] || 0) + 1;
console.log("edition counts:", JSON.stringify(eds));
const mephit = raw.filter(r => r.id === "mephit");
console.log("mephit:", JSON.stringify(mephit, null, 1));
const noZh = raw.filter(r => !r.name_zh).map(r => r.id);
console.log("roles without name_zh:", JSON.stringify(noZh));
const noUq = raw.filter(r => !r.unique_note).map(r => r.id);
console.log("roles without unique_note:", JSON.stringify(noUq));
const fieldNames = new Set(); raw.forEach(r => Object.keys(r).forEach(k => fieldNames.add(k)));
console.log("all field names:", JSON.stringify([...fieldNames]));
